//go:build ignore

package main

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

const (
	tableTiles  = 15
	tableCopies = 5
)

type mapSource struct {
	file    string
	static  string
	entries int
	blob    string
}

type tableSource struct {
	file   string
	name   string
	kinds  int
	goName string
}

var (
	integer     = regexp.MustCompile(`[0-9]+`)
	lineComment = regexp.MustCompile(`//[^\n]*`)
)

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: go run extract_maps.go <xiangting crate directory>")
	}
	standard := filepath.Join(os.Args[1], "src", "standard")

	maps := []mapSource{
		{"shupai_map.rs", "SHUPAI_REPLACEMENT_NUMBER_MAP", 405350, "shupai_replacement_number.bin"},
		{"zipai_map.rs", "ZIPAI_REPLACEMENT_NUMBER_MAP", 43130, "zipai_replacement_number.bin"},
	}
	for _, source := range maps {
		blob, err := extractMap(filepath.Join(standard, source.file), source)
		if err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(source.blob, blob, 0o644); err != nil {
			log.Fatal(err)
		}
		fmt.Printf("%s %x\n", source.blob, sha256.Sum256(blob))
	}

	tables := []tableSource{
		{"shupai_table.rs", "SHUPAI_TABLE", 9, "shupaiHash"},
		{"zipai_table.rs", "ZIPAI_TABLE", 7, "zipaiHash"},
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by extract_maps.go; DO NOT EDIT.\n\npackage shanten\n")
	for _, source := range tables {
		if err := writeTable(&out, filepath.Join(standard, source.file), source); err != nil {
			log.Fatal(err)
		}
	}
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("lookup_hash.go", formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

func arrayBody(path, name string) (string, error) {
	source, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	text := string(source)
	start := strings.Index(text, " "+name+":")
	if start < 0 {
		return "", fmt.Errorf("%s: no %s", path, name)
	}
	text = text[start:]
	open := strings.Index(text, "= [")
	end := strings.Index(text, "];")
	if open < 0 || end < open {
		return "", fmt.Errorf("%s: %s is not an array literal", path, name)
	}
	return lineComment.ReplaceAllString(text[open+len("= ["):end], ""), nil
}

func extractMap(path string, source mapSource) ([]byte, error) {
	body, err := arrayBody(path, source.static)
	if err != nil {
		return nil, err
	}
	values := integer.FindAllString(body, -1)
	if len(values) != source.entries {
		return nil, fmt.Errorf("%s: %d entries, want %d", path, len(values), source.entries)
	}
	blob := make([]byte, 0, 4*len(values))
	for _, value := range values {
		number, err := strconv.ParseUint(value, 10, 32)
		if err != nil {
			return nil, err
		}
		blob = append(blob, byte(number), byte(number>>8), byte(number>>16), byte(number>>24))
	}
	return blob, nil
}

func writeTable(out *bytes.Buffer, path string, source tableSource) error {
	body, err := arrayBody(path, source.name)
	if err != nil {
		return err
	}
	values := integer.FindAllString(body, -1)
	if len(values) != source.kinds*tableTiles*tableCopies {
		return fmt.Errorf("%s: %d values, want %d", path, len(values), source.kinds*tableTiles*tableCopies)
	}
	fmt.Fprintf(out, "\nvar %s = [%d][%d][%d]uint32{\n", source.goName, source.kinds, tableTiles, tableCopies)
	for kind := range source.kinds {
		out.WriteString("{\n")
		for tiles := range tableTiles {
			row := values[(kind*tableTiles+tiles)*tableCopies:][:tableCopies]
			fmt.Fprintf(out, "{%s},\n", strings.Join(row, ", "))
		}
		out.WriteString("},\n")
	}
	out.WriteString("}\n")
	return nil
}
